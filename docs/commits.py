# Вопрос 1. Опишите своими словами назначение каждого типа коммитов:
#
# feat — добавление новой функциональности в проект.
# fix — исправление ошибок в работе программы.
# docs — изменение документации, например README или комментариев с
# пояснениями.
# style — изменение оформления кода без влияния на его работу:
# отступы, пробелы, форматирование.
# refactor — переработка структуры кода без изменения его поведения.
# test — добавление или исправление тестов.
# build — изменения в системе сборки проекта или его зависимостях.
# ci — настройка автоматических проверок, сборки и развёртывания через
# CI/CD.
# perf — оптимизация производительности программы без изменения её
# функциональности.
# chore — вспомогательные технические изменения, не относящиеся
# напрямую к функциональности, например настройка инструментов
# разработки или обслуживание репозитория.
