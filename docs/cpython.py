# # CPython и PyPy
#
# ## Теоретические вопросы
#
# ### 1. Что такое CPython и чем он отличается от Python?
#
# Python — язык программирования, а CPython — его
# основная реализация, написанная преимущественно на C.
# CPython включает компилятор байт-кода, виртуальную
# машину и среду выполнения Python.
#
# ### 2. Ответьте на вопрос с изображения
#
# На изображении нет отдельного вопроса, а приведено
# сравнение Python и CPython. Это не два разных языка:
# Python задаёт правила языка, а CPython их реализует.
#
# ### 3. Сколько существует реализаций Python?
#
# Точного фиксированного количества нет. Кроме CPython,
# существуют PyPy, Jython, IronPython, GraalPy и другие.
# MicroPython реализует подмножество языка Python.
# Самая распространённая реализация — CPython.
#
# ### 4. На каком языке написан CPython?
#
# Преимущественно на C. Часть стандартной библиотеки
# написана на самом Python.
#
# ### 5. (Опционально) Кто создал CPython?
#
# Гвидо ван Россум — создатель Python и его исходной
# реализации, которая впоследствии получила имя CPython.
#
# ### 6. Почему Python считается быстрым?
#
# Python не обязательно быстрее компилируемых языков.
# Сам CPython часто медленнее C или C++ в вычислительных
# циклах. Но библиотеки с кодом на C, C++ и других
# компилируемых языках позволяют выполнять многие
# задачи эффективно. Скорость зависит от нагрузки.
#
# ### 7. Путь к интерпретатору CPython на компьютере
#
# `/usr/bin/python3.12`
#
# ## Структура CPython
#
# ### 8. Что содержится в папке Include?
#
# В исходниках CPython каталог `Include/` содержит
# заголовочные файлы C (`.h`). Они объявляют типы,
# структуры, функции и макросы для внутреннего кода
# CPython и его C API. Например, `Python.h` используется
# при создании расширений Python на C. В установленной
# системе заголовки могут находиться в
# `/usr/include/python3.12/`.
#
# ### 9. Где найти исходный код CPython?
#
# Официальный репозиторий:
# https://github.com/python/cpython
#
# ### 10. Как интерпретатор CPython выполняет код?
#
# 1. Читает исходный код Python.
# 2. Разбирает его и формирует синтаксическое дерево.
# 3. Компилирует дерево в байт-код Python.
# 4. Исполняет байт-код в виртуальной машине CPython.
#
# При импорте модулей байт-код может кэшироваться
# в файлах `.pyc` внутри каталога `__pycache__/`.
#
# ## Запуск файла с помощью CPython
#
# ### 11. Какая команда запускает файл через CPython?
#
# ```bash
# python3 example.py
# ```
#
# ### 12. Можно ли запускать текстовые файлы и почему?
#
# Да, например `python3 example.txt`, если файл
# содержит корректный код Python. При прямом запуске
# файла интерпретатору не требуется расширение `.py`.
#
# ### 13. Как указать пути к интерпретатору и файлу?
#
# Сначала указывается путь к интерпретатору, затем —
# путь к запускаемому файлу:
#
# ```bash
# /usr/bin/python3.12 /home/mikhail/example.py
# ```
#
# ### 14. Чем PyPy отличается от CPython?
#
# PyPy — альтернативная реализация Python с JIT:
# часто исполняемые участки кода компилируются
# в машинные инструкции во время работы программы.
# На некоторых задачах PyPy быстрее CPython, но
# результат зависит от программы и используемых
# библиотек.
#
# ### 15. Почему PyPy подходит не для всех проектов?
#
# Не все расширения, рассчитанные на C API CPython,
# одинаково хорошо работают с PyPy. Возможны проблемы
# совместимости или производительности библиотек.
# Кроме того, JIT требует времени на разогрев и может
# расходовать больше памяти. Преимущество не всегда есть.
#
# ### 16. Где можно скачать PyPy?
#
# Официальный сайт: https://www.pypy.org/
#
# ### 17. Как установить PyPy после скачивания?
#
# Скачать сборку для своей ОС, распаковать архив,
# при необходимости добавить папку с исполняемым
# файлом в `PATH`. Проверить установку командой:
#
# ```bash
# pypy3 --version
# ```
#
# Также в некоторых ОС доступен пакет `pypy3`.
#
# ### 18. Как запустить файл через PyPy?
#
# ```bash
# pypy3 example_pypy.py
# ```
#
# Можно указать абсолютные пути к интерпретатору
# и файлу, как в случае с CPython.
#
# ### 19. Почему PyPy может работать быстрее CPython?
#
# JIT-компилятор обнаруживает часто выполняемый код,
# компилирует его в машинные инструкции и оптимизирует
# его во время выполнения. Это сокращает накладные
# расходы на интерпретацию повторяющихся операций.
