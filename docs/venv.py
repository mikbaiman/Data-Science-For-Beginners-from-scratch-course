# ### Создание и активация окружения
#
# 1. Что делает команда python -m venv venv?
#
# Создаёт виртуальное окружение с названием "venv"
#
# 2. Что делает каждая команда в списке ниже?
#
# pip list  -> показывает установленные пакеты
#
# pip freeze > requirements.txt -> сохраняет список зависимостей с их
# версиями в текстовый файл с названием requirements
#
# pip install -r requirements.txt -> устанавливает зависимости
# согласно версиям
#
# 3. Что делает каждая команда в списке ниже?
#
# conda env list -> показывает список окружений
#
# conda create -n env_name python=3.5 -> создает окружение с Python
# версии 3.5
#
# conda env update -n env_name -f file.yml -> обновляет окружение на
# основании файла file.yml
#
# source activate env_name -> включение окружения
#
# source deactivate -> выключение окружения
#
# conda clean -a -> очистка кэша
#
# Пояснение: Команды source activate и source deactivate
# использовались в старых версиях Conda. Начиная с Conda 4.4
# рекомендуется использовать conda activate env_name и conda
# deactivate.
#
