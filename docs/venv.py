# 8. Что делают эти команды?
#
# pip install -r requirements.txt -> Читает файл requirements.txt и
# устанавливает перечисленные Python-библиотеки, указанные версии
#
# conda env create -f environment.yml -> Создаёт новое окружение Conda
# по конфигурации, записанной в YAML-файле
#
# 9. Что делают эти команды?
#
# pip list  -> Выводит таблицу установленных Python-пакетов и их
# версий в текущем окружении
#
# pip show <название_пакета> -> Показывает подробную информацию об
# определённом пакете: версию, описание, расположение на диске и
# зависимости
#
# conda list -> Отображает пакеты, установленные в текущем окружении
# Conda, включая их версии, сборки и каналы установки
#
# 10. Где по умолчанию больше пакетов — в venv/pip или в conda? Почему
# data scientists используют conda?
#
# В стандартном виртуальном окружении venv обычно установлен
# минимальный набор инструментов Python, а дополнительные библиотеки
# устанавливаются через pip. В Conda количество предустановленных
# пакетов зависит от типа окружения: базовое окружение Anaconda обычно
# содержит больше библиотек, тогда как новое окружение Miniconda может
# быть практически пустым.
# Conda особенно удобна для Data Science и Machine Learning, ведь она
# позволяет устанавливать не только Python-пакеты, но и системные
# библиотеки, упрощает управление версиями Python и зависимостями
#
